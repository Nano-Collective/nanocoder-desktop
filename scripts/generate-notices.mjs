import {
	existsSync,
	readdirSync,
	readFileSync,
	realpathSync,
	writeFileSync,
} from 'node:fs';
import path from 'node:path';
import {
	collectTree,
	licenceProblems,
	packageDirFromModuleId,
	readPackage,
	renderNotices,
} from './lib/notices.mjs';

// Builds the third-party notices (REL-06). Three modes:
//   (default)  the desktop's THIRD-PARTY-NOTICES.txt, from the packages its builds bundle
//   --check    the same, compared with the committed file; fails when it is out of date
//   --runtime  the notices for the Node and Nanocoder staged in .cache/runtime, written beside them
const root = path.resolve(import.meta.dirname, '..');
const policy = JSON.parse(
	readFileSync(path.join(root, 'scripts', 'notice-policy.json'), 'utf8'),
);
const mode = process.argv[2] ?? '';
const fail = lines => {
	for (const line of lines) console.error(line);
	process.exit(1);
};

// The packages in the desktop's own builds: what the bundler pulled in, the font files, and the
// production dependencies that electron-builder copies beside the app (the native terminal addon).
function desktopPackages() {
	const folder = path.join(root, '.cache', 'bundled-modules');
	const lists = existsSync(folder)
		? readdirSync(folder).filter(name => name.endsWith('.json'))
		: [];
	if (lists.length === 0)
		fail(['No bundled module lists found. Run pnpm build first.']);
	const bundled = new Map();
	for (const name of lists)
		for (const id of JSON.parse(
			readFileSync(path.join(folder, name), 'utf8'),
		)) {
			const where = packageDirFromModuleId(id);
			if (where && !bundled.has(where.dir)) bundled.set(where.dir, where);
		}
	for (const name of policy.alsoShipped) {
		const dir = path.join(root, 'node_modules', ...name.split('/'));
		bundled.set(dir, {name, dir});
	}
	const own = [...bundled.values()].map(item => readPackage(item.dir));
	const names = new Set(own.map(item => `${item.name}@${item.version}`));

	const beside = new Map();
	const dependencies = Object.keys(
		JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
			.dependencies ?? {},
	);
	const find = (from, name) => {
		for (let dir = from; path.dirname(dir) !== dir; dir = path.dirname(dir)) {
			if (path.basename(dir) === 'node_modules') continue;
			const candidate = path.join(dir, 'node_modules', ...name.split('/'));
			if (existsSync(path.join(candidate, 'package.json')))
				return realpathSync(candidate);
		}
		return undefined;
	};
	const walk = dir => {
		if (beside.has(dir)) return;
		const item = readPackage(dir);
		beside.set(dir, item);
		const json = JSON.parse(
			readFileSync(path.join(dir, 'package.json'), 'utf8'),
		);
		for (const name of Object.keys({
			...json.dependencies,
			...json.optionalDependencies,
		})) {
			const next = find(dir, name);
			if (next) walk(next);
		}
	};
	for (const name of dependencies) {
		const start = find(root, name);
		if (!start) fail([`Production dependency ${name} is not installed`]);
		walk(start);
	}
	const extra = [...beside.values()].filter(
		item => !names.has(`${item.name}@${item.version}`),
	);
	return {own, extra};
}

function desktopNotices() {
	const {own, extra} = desktopPackages();
	const problems = licenceProblems([...own, ...extra], policy, {
		reportUnusedExceptions: false,
	});
	if (problems.length > 0) fail(problems);
	return renderNotices({
		title: 'Third-party notices for Nanocoder Desktop',
		intro: `This app includes the open source packages below, each under its own licence, which is reproduced with it.

The Node.js and Nanocoder that the app runs ship in resources/runtime with their own notices (runtime/THIRD-PARTY-NOTICES.txt) and Node.js's licence (runtime/node/LICENSE). Electron's and Chromium's licences are in the LICENSE.electron.txt and LICENSES.chromium.html files that Electron ships with the app.

This file is generated by scripts/generate-notices.mjs from the packages the build bundles. Do not edit it by hand.`,
		sections: [
			{heading: 'Bundled into the app', packages: own},
			{heading: 'Installed beside the app', packages: extra},
		],
	});
}

function runtimeNotices() {
	const stage = path.join(root, '.cache', 'runtime');
	const tree = collectTree(path.join(stage, 'nanocoder', 'node_modules'));
	if (tree.length === 0)
		fail(['No staged runtime found. Run pnpm prepare:runtime first.']);
	const problems = licenceProblems(tree, policy);
	if (problems.length > 0) fail(problems);
	const nanocoder = tree.filter(
		item => item.name === '@nanocollective/nanocoder',
	);
	return renderNotices({
		title: 'Third-party notices for the runtime of Nanocoder Desktop',
		intro: `These are the Nanocoder this app runs and every package installed with it, each under its own licence, which is reproduced with it.

The Node.js that runs it is licensed in runtime/node/LICENSE, which also covers what Node.js bundles. The desktop's own notices are in THIRD-PARTY-NOTICES.txt.

This file is generated at build time from the packages that are staged in this app. Do not edit it by hand.`,
		sections: [
			{heading: 'Nanocoder', packages: nanocoder},
			{
				heading: "Nanocoder's dependencies",
				packages: tree.filter(
					item => item.name !== '@nanocollective/nanocoder',
				),
			},
		],
	});
}

if (mode === '--runtime') {
	const file = path.join(root, '.cache', 'runtime', 'THIRD-PARTY-NOTICES.txt');
	writeFileSync(file, runtimeNotices());
	console.log(`Wrote ${file}`);
} else {
	const committed = path.join(root, 'THIRD-PARTY-NOTICES.txt');
	const text = desktopNotices();
	if (mode === '--check') {
		const current = existsSync(committed)
			? readFileSync(committed, 'utf8')
			: '';
		if (current.replace(/\r\n/g, '\n') !== text)
			fail([
				'THIRD-PARTY-NOTICES.txt is out of date. Run pnpm notices:generate and commit the result.',
			]);
		console.log('THIRD-PARTY-NOTICES.txt is up to date');
	} else {
		writeFileSync(committed, text);
		console.log(`Wrote ${committed}`);
	}
}
